/// Uint8List üzerinde `videoKodegi`nin beklediği okuyucu.
///
/// GERÇEK MOTORU TAKLİT EDER: dosya sonunu aşan istek KISA döner, tamamen
/// dışarıdaki istek BOŞ döner (`video_islem_io.dart:parca` sözleşmesi).
Future<Uint8List> Function(int, int) bellektenOku(Uint8List veri) =>
    (bas, adet) async {
      if (bas < 0 || adet <= 0 || bas >= veri.length) return Uint8List(0);
      final son = bas + adet > veri.length ? veri.length : bas + adet;
      return Uint8List.sublistView(veri, bas, son);
    };
